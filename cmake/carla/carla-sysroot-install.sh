#!/usr/bin/env bash
# Collect the artifacts a downstream consumer (src/carla) needs to compile and
# link against libcarla-client.a into one install prefix ("sysroot").
#
# CARLA 1.0 vendors its dependencies with FetchContent and marks them
# EXCLUDE_FROM_ALL, so `cmake --install` only produces libcarla-client.a and
# the carla/ headers. But carla's *public* headers #include <rpc/msgpack.hpp>,
# <boost/...>, <Recast.h>, <Detour*.h> and <png.h>, and the link line needs
# the compiled archives (Boost, rpclib, Recast, libpng, zlib). Copy them all
# into <prefix>/include and <prefix>/lib so a consumer only has to know the
# prefix — and so the consumer provably uses the same headers libcarla was
# compiled against (mixing system Boost 1.74 with the vendored 1.90 would be
# an ODR time bomb).
#
# Usage: carla-sysroot-install.sh <carla-build-dir> <prefix>
# (headers of the vendored dependencies come from the FetchContent sources
# under <build-dir>/_deps/*-src; CARLA picks the versions, we only collect.)
set -euo pipefail

BUILD_DIR=${1:?usage: carla-sysroot-install.sh <carla-build-dir> <prefix>}
PREFIX=${2:?}
DEPS="$BUILD_DIR/_deps"

mkdir -p "$PREFIX/include/boost"
# Boost headers: merge the modular libs/*/include/boost subtrees into a
# single include/boost (this is what Boost's own install step does; the
# per-library subtrees are disjoint). libcarla's own compile flags use
# exactly these directories, so no generated headers are involved.
found_libs=0
for inc in "$DEPS"/boost-src/libs/*/include; do
  [ -d "$inc/boost" ] || continue
  cp -Rn "$inc/boost/." "$PREFIX/include/boost/"
  found_libs=$((found_libs + 1))
done
[ "$found_libs" -gt 0 ] || { echo "sysroot: no boost headers found in $DEPS" >&2; exit 1; }

# rpclib headers (carla/MsgPack.h includes <rpc/msgpack.hpp>).
[ -d "$DEPS/rpclib-src/include/rpc" ] || { echo "sysroot: missing $DEPS/rpclib-src/include/rpc" >&2; exit 1; }
cp -R "$DEPS/rpclib-src/include/rpc" "$PREFIX/include/"

# Recast & Detour headers (carla/road navigation headers include them flat).
for d in Recast/Include Detour/Include DetourCrowd/Include; do
  find "$DEPS/recastnavigation-src/$d" -name '*.h' -exec cp -f {} "$PREFIX/include/" \;
done

# libpng headers: png.h/pngconf.h from the source, pnglibconf.h generated by
# the build — consumers that include <png.h> (CarlaImageSink) must pair with
# the vendored libpng.a, not a system libpng.
cp -f "$DEPS/libpng-src/png.h" "$DEPS/libpng-src/pngconf.h" "$PREFIX/include/"
cp -f "$DEPS/libpng-build/pnglibconf.h" "$PREFIX/include/"

# Compiled archives: Boost (all that the superbuild produced) ...
shopt -s nullglob
boost_archives=("$DEPS"/boost-build/libs/*/libboost_*.a)
[ "${#boost_archives[@]}" -gt 0 ] || { echo "sysroot: no boost archives found" >&2; exit 1; }
cp -f "${boost_archives[@]}" "$PREFIX/lib/"

# ... and the remaining vendored dependencies.
copy_one() {
  local src=$1
  [ -f "$src" ] || { echo "sysroot: missing $src" >&2; exit 1; }
  cp -f "$src" "$PREFIX/lib/"
}
copy_one "$DEPS/rpclib-build/librpc.a"
copy_one "$DEPS/recastnavigation-build/Recast/libRecast.a"
copy_one "$DEPS/recastnavigation-build/Detour/libDetour.a"
copy_one "$DEPS/recastnavigation-build/DetourCrowd/libDetourCrowd.a"
copy_one "$DEPS/libpng-build/libpng.a"
copy_one "$DEPS/zlib-build/libz.a"

echo "sysroot: boost headers ($found_libs libs) + rpc/recast/png headers, $(ls "$PREFIX"/lib/*.a | wc -l) archives -> $PREFIX"
